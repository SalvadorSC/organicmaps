void AppendFgcSchemeTracks(std::vector<RailTrack> & tracks)
{
  tracks.reserve(tracks.size() + sizeof(kFgcShapes) / sizeof(kFgcShapes[0]));
  for (auto const & row : kFgcShapes)
  {
    RailTrack track;
    track.m_ref = row.m_line;
    track.m_colored = false;
    track.m_shape.reserve(row.m_count);
    for (size_t i = 0; i < row.m_count; ++i)
      track.m_shape.push_back({row.m_points[i][0], row.m_points[i][1]});
    tracks.push_back(std::move(track));
  }
}
